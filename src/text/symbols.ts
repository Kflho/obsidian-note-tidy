/**
 * 逐符号的空格规则（纯数据 + 纯函数，不依赖 Obsidian API）。
 *
 * ## 一条总原则：空格只用来分隔**不同语言的内容**
 *
 * 中文排版规范（W3C [中文排版需求 clreq](https://www.w3.org/TR/clreq/)）里，"加空隙"只有一种情况：
 * 汉字与**西文字母、阿拉伯数字**之间用不多于四分之一个汉字宽的字距或空白（§6.3.3）；
 * 同一个 §6.3.3 还写着「在中文点号前后、中文开始夹注符号之后、结束夹注符号之前的
 * 西文字母或阿拉伯数字，不调整字距或加入空白」，§1.2 更直接：汉字与标点都是 1:1 方块，
 * "**无缝隙并列**"。CSS 的 `text-autospace` 默认值（`ideograph-alpha` + `ideograph-numeric`）
 * 同样只在中西文之间加空隙，标点要另外显式写 `punctuation` 才加。
 *
 * 所以本表的 `space` 一律读作「**与西文内容（字母 / 数字 / 公式 / 行内代码）之间留一格**」：
 * 邻居是中文、全角标点、另一个符号时都按贴紧处理（已有的空格一并收掉）。
 *
 * - `甲&乙` → `甲&乙`（`&` 是 Unicode 标点 Po，中文与标点无缝隙）、`甲 & 乙` → `甲&乙`
 * - `A & B`、`$A$ & $B$` → 保留那一格（西文内容之间）
 * - `, ：`、`| ：`、`：&`、`7. 并列：&` → 全部贴紧（符号之间也不加）
 *
 * ## 逐符号规则
 *
 * - 英文符号 1：`,` `.` `!` `?` `:` 后面有空格（`word, word`）；
 * - 英文符号 3：`...` 的现代写法中前后没有空格；
 * - 通用符号 3（包裹符号）：括号、引号等**自己不添空格** —— 内侧贴紧、外侧按"分隔语言"办；
 * - 通用符号 4：`→` 与前后内容间要加空格；`|` 单独一个左右要加空格 —— 这两条写在
 *   笔记的「**格式** → 标点符号 → 通用符号」一节，讲的是公式代码里的写法（公式里由
 *   「公式排版」latex.ts 负责）；正文里按上面那条总原则走；
 * - 通用符号 2：`&` 前后有内容都要加排版空格（同上：正文里只与西文内容留一格）；
 * - 通用符号 3：`^` 与前后内容间不加空格；
 * - 标记命名 4、5：`：` 是"内容后标注或解释"（紧跟内容）；`/`（或、别名）贴紧，没有空格规则。
 *
 * ## 包裹符号：圈住的东西是一个整体
 *
 * 括号 `（）` / `()`、书名号 `《》` `〈〉`、引号 `“”` `‘’`、成对的 `"` 是**表示"里面的内容"**
 * 的符号 —— 它们负责"圈"，**本身不算内容**。
 *
 * 通用符号 3 的子条目「包裹符号：括号、引号等，内外均没有空格」说的，意思是**包裹符号自己不添空格**，不是"把外侧已有的空格也删掉"：
 * 内侧的填充空格要删，外侧不主动加、也不删**语言自带**的词距 —— 西文旁那一格是英文词距
 * （`appendix (page 3)`、`He said "hello" loudly`），中文旁本来就没有词距
 * （`他说 "你好" 了` → `他说"你好"了`，正如 `he said 你好(nihao)` 里括号与中文之间没有空格）。
 *
 * 1. **内侧不留空格**：`（ 内容 ）` → `（内容）`、`《 书名 》` → `《书名》`、`“ 引文 ”` → `“引文”`；
 * 2. **里面的符号不朝包裹符号要空格**：`（+）`、`（→）`、`（|）`、`"+"` 都贴紧；
 * 3. **圈住的那段文字内部照旧**：`《新 吊带袜天使》` 里专有名词的那一格保留（文字格式 4）；
 * 4. **外侧照"分隔语言"办**：西文内容旁留一格（`He said "hello" loudly`），中文旁贴紧
 *    （`他说 "你好" 了` → `他说"你好"了`）。
 *
 * ## 竖线：先分清"数学记号里的"还是"正文里的"
 *
 * 全库实测（`|` 出现在正文而非表格 / 公式 / 双链里的地方）只有四种：
 * - `如（）、||等` —— 包裹符号，`||` 贴紧，两边都不加空格；
 * - `$0.00$ | $0.30$: $11.77$` —— 正文里的分隔符，西文内容之间各一格；
 * - `|：单独一个 | 左右要加空格` —— 被提到的符号，与 `：`、与中文都贴紧；
 * - `x̂_{k|k}`、`P(A|B)`、`|f_{y}|` —— 数学记号里的一部分，**贴紧、一个字符都不动**。
 *
 * 所以「单独一个 `|`」的判据是**贴不贴数学记号**：紧贴字母 / 数字 / `_` `^` `{` `}` `\`
 * 的竖线属于数学记号（规则 180 说的"单独一个"不包括它），其余才算正文里的独立符号。
 * `||`（连续两个及以上）整体是包裹符号，按 176 贴紧。
 */

/** 一个符号对自己左侧 / 右侧的要求 */
export type SymbolPad =
	/** 留一个空格 */
	| 'space'
	/** 不留空格 */
	| 'none'
	/** 不动，交给别的规则 */
	| 'keep';

export interface SymbolRule {
	left: SymbolPad;
	right: SymbolPad;
	/** 笔记里的出处，设置面板与测试对着它看 */
	source: string;
	/**
	 * `space` 的生效范围（默认 `content`）。
	 *
	 * - `content`：与**任何内容**（中文 / 西文 / 数字 / 公式 / 行内代码）之间留一格 ——
	 *   英文标点 `, . ! ? :` 用这一档（"英文符号遵循英文规则，在中文间可以有空格"：
	 *   `word, word`、`here. 中文`、`1.矩阵` → `1. 矩阵`）；
	 * - `latin`：只与**西文内容**（字母 / 数字 / 公式 / 行内代码）之间留一格，
	 *   中文旁、符号旁一律贴紧（已有的空格收掉）—— `&` `|` `→` 与引号外侧用这一档
	 *   （`A & B` 留一格，`甲 & 乙` → `甲&乙`、`他说 "你好" 了` → `他说"你好"了`）。
	 */
	scope?: 'content' | 'latin';
}

