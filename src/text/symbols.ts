/**
 * **故意不进表的符号**：`~`（通用符号 6）、`-`（通用符号 7）。
 *
 * 规范说它们"两边都不加空格"，这里用**不写规则**来实现 —— 既不添空格，也不删作者已经写的空格：
 * `甲 ~ 乙` 与 `甲~乙` 都原样保留（`约 ~5 个` 里只会被"中文 ↔ 数字"那条规则收掉一格，
 * 与 `~` 本身无关）。排版不替作者补他没写的东西，也不删他写的东西 ——
 * 想更激进地"抹平已有空格"，得先有明确需求再加规则。
 */

/**
 * 半角引号（成对时才认）：也是包裹符号 —— **内侧不留空格、外侧按"分隔语言"办**。
 *
 * 内侧：`" + "` → `"+"`、`" 引文 "` → `"引文"`（通用符号 3：包裹符号自己不添空格）。
 * 外侧：西文内容旁留一格（`He said "hello" loudly`，那是英文自己的词距），中文旁贴紧
 * （`他说 "你好" 了` → `他说"你好"了`）。
 * 落单的引号（`2" 的管子`）不成对，一个字符都不动。
 */
export const OPEN_QUOTE_RULE: SymbolRule = {
	left: 'space',
	right: 'none',
	source: '通用符号 3（包裹符号）',
	scope: 'latin',
};
export const CLOSE_QUOTE_RULE: SymbolRule = {
	left: 'none',
	right: 'space',
	source: '通用符号 3（包裹符号）',
	scope: 'latin',
};

/**
 * 包裹符号（`||`）：前后都不加空格（通用符号 3 的包裹符号子条目）。外侧给 `keep` ——
 * 紧贴内容的那一侧本来就贴着，而"范数 ||x|| 的写法"这种外侧留白是文字间距规则的事，
 * 包裹符号不该去删它。
 */
export const PACKAGE_RULE: SymbolRule = { left: 'keep', right: 'keep', source: '通用符号 3' };

/** 紧贴这些字符的竖线属于数学记号（`|x|`、`P(A|B)`、`x̂_{k|k}`、`\left\|`），不按正文符号处理 */
const MATH_GLUE_RE = /[A-Za-z0-9_^{}\\]/;

/** 组合用记号（`x̂` 里的 `̂` U+0302）：它也算"贴着字母"，竖线紧挨着它同样属于数学记号 */
const COMBINING_FROM = '\u0300';
const COMBINING_TO = '\u036f';

/** 这个字符算不算"数学记号的一部分" */
export function isMathGlue(char: string): boolean {
	return MATH_GLUE_RE.test(char) || (char >= COMBINING_FROM && char <= COMBINING_TO);
}

/**
 * 广义符号字符集合：只为判断"这个标点是不是在被罗列、被解释"用，不参与空格表。
 *
 * 笔记里大量出现 `1. , /. /! /? /:：后面有空格`、`|：单独一个 | 左右要加空格`、
 * `如, ：` 这类**在讲符号本身**的写法：夹在两个符号中间的标点是"被提到的符号"，
 * 不该被当成中文标点换成全角，也不该被别的规则顺手删掉空格。
 */
export const SYMBOL_CHARS = new Set<string>([...'/\\=+<>*~^_#@%$&|→×÷±≤≥≠']);

/** 这个字符算不算"广义符号" */
export function isSymbolChar(char: string): boolean {
	return SYMBOL_CHARS.has(char);
}
