/**
 * 半角引号（成对时才认）：也是包裹符号，**内侧不留空格**。
 *
 * 204 行「包裹符号是例外，因为是突出里面内容，应该写成 `(+)`、`"+"`」——
 * 两个半边只负责圈，所以 `" + "` → `"+"`、`" 引文 "` → `"引文"`（内侧收掉多余空格）。
 * **外侧不动**：`他说 "你好" 了` 里引号与中文之间那两格留着 —— 209 行说的
 * "左引号前、右引号后没有空格"是书写要求，插件不主动去删（删了不好回头）。
 * 落单的引号（`2" 的管子`）不成对，一个字符都不动。
 */
