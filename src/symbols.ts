/**
 * 逐符号的空格规则（纯数据 + 纯函数，不依赖 Obsidian API）。
 *
 * 笔记里的规则是**逐符号**写的，不是一个"符号周围一律加空格"：
 * - 英文符号 1：`,` `.` `!` `?` `:` 后面有空格；
 * - 英文符号 2：`"` 左引号后、右引号前有空格 —— **右引号后面没有空格**；
 * - 英文符号 3：`()` 前后没有空格、`...` 前后没有空格；
 * - latex 符号格式 4：`→` 与前后内容间要加空格；`|` **单独一个**时左右要加空格；
 * - latex 符号格式 5：`&` 前后有内容都要加排版空格；
 * - latex 符号格式 2：`^` 与前后内容间不加空格；包裹符号（`()`、`||`）前后不加空格；
 * - 标记命名 4、5：`：` 是"内容后标注或解释"（紧跟左边的符号或内容）；
 *   `/`（或、别名）与 `A/B` 一样贴紧，本身没有空格规则。
 *
 * 标点符号·概论 4「符号与符号之间」把这件事坐实了：符号自己的规则是**强制**的，
 * 不因为旁边也是符号就跳过 —— `如, ：`、`| ：`、`→ ：` 都要留那一格，
 * 而 `"：`（右引号后面）不留、`^：`（修饰符号前后不空）也不留。
 *
 * 两条规则打架时（`：` 说"前不留空格"，`|` 说"右边要空格"）的裁决：
 * **要空格的一方赢**；两边都说不留才删。这样 `如, ：` 保持一格，
 * 而 `中文 ：内容` 仍然收成 `中文：内容`。
 *
 * ## 包裹符号：圈住的东西是一个整体
 *
 * 括号 `（）` / `()`、书名号 `《》` `〈〉`、引号 `“”` `‘’` 是**表示"里面的内容"**的符号 ——
 * 它们负责"圈"，**本身不算内容**。由此得到四条：
 *
 * 1. **内侧不留空格**：`（ 内容 ）` → `（内容）`、`《 书名 》` → `《书名》`、`“ 引文 ”` → `“引文”`
 *    —— 包裹符号不算内容，所以它和被圈住的东西之间没有"内容与内容之间"那一格；
 * 2. **里面的符号不朝包裹符号要空格**：`（+）`、`（→）`、`（|）`、`“+”` 都贴紧，
 *    不写成 `（ + ）` —— 那里面是"被提到的符号"（在讲这个符号本身），不是正文里的运算符；
 * 3. **圈住的那段文字内部照旧**：`《新 吊带袜天使》` 里专有名词的那一格保留（文字格式 4）；
 * 4. **外侧按"内容 ↔ 标点"处理**：`中文（说明）` 贴紧、`如（+）等` 贴紧、`函数 |x| 的值` 留一格。
 *
 * 一句话：**包裹符号负责圈，圈内是整体 —— 两个半边不算内容，所以内侧永远贴紧；
 * 里面的东西只在"整体对外"时才算内容。**
 *
 * ## 竖线：先分清"数学记号里的"还是"正文里的"
 *
 * 全库实测（`|` 出现在正文而非表格 / 公式 / 双链里的地方）只有四种：
 * - `如（）、||等` —— 包裹符号，`||` 贴紧，两边都不加空格；
 * - `$0.00$ | $0.30$: $11.77$` —— 正文里的分隔符，左右各一格（latex 符号格式 4）；
 * - `|：单独一个 | 左右要加空格` —— 被提到的符号，`|` 与 `：` 之间要一格；
 * - `x̂_{k|k}`、`P(A|B)`、`|f_{y}|` —— 数学记号里的一部分，**贴紧、一个字符都不动**。
 *
 * 所以「单独一个 `|`」的判据是**贴不贴数学记号**：紧贴字母 / 数字 / `_` `^` `{` `}` `\`
 * 的竖线属于数学记号（规则 180 说的"单独一个"不包括它），其余才算正文里的独立符号。
 * `||`（连续两个及以上）整体是包裹符号，按 176 贴紧。
 */

/** 一个符号对自己左侧 / 右侧的要求 */
export type SymbolPad =
	/** 留一个空格 */
	| 'space'
	/** 不留空格 */
	| 'none'
	/** 不动，交给别的规则 */
	| 'keep';

export interface SymbolRule {
	left: SymbolPad;
	right: SymbolPad;
	/** 笔记里的出处，设置面板与测试对着它看 */
	source: string;
	/**
	 * 只在邻居是**内容**（中文 / 英文 / 数字 / 公式 / 行内代码）时作主。
	 *
	 * 只有 `：` 用这一条：标记命名 4 说的是"**内容**后标注或解释" —— 它紧贴的是它解释的那个
	 * 内容；左边是符号时（`如, ：`、`| ：`）它不作主，让那个符号按自己的规则决定那一格。
	 *
	 * 注意别的符号**没有**这个限定：像「`&` 前后有内容都要加排版空格」里的"有内容"，
	 * 是所有空格规则共同的前提（没东西的地方当然没有空格），不是给 `&` 开的后门 ——
	 * 每条规则真正要回答的只有两个问题：左边要不要一格、右边要不要一格。
	 */
	contentOnly?: boolean;
}

